-- Apple compliance tables + user_profiles additions
-- Part 4.1 of HANDOFF.md

-- user_profiles additions (used by Settings UI)
ALTER TABLE public.user_profiles
  ADD COLUMN IF NOT EXISTS email text,
  ADD COLUMN IF NOT EXISTS contact_info text;

-- content reports (Apple Guideline 1.2)
CREATE TABLE IF NOT EXISTS public.content_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_id text NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
  content_type text NOT NULL CHECK (content_type IN ('post','comment','message','user')),
  content_id text NOT NULL,
  reason text NOT NULL,
  details text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','reviewed','dismissed')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS content_reports_status_idx
  ON public.content_reports (status, created_at DESC);
CREATE INDEX IF NOT EXISTS content_reports_reporter_idx
  ON public.content_reports (reporter_id);

ALTER TABLE public.content_reports ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "users can insert their own reports" ON public.content_reports;
CREATE POLICY "users can insert their own reports" ON public.content_reports
  FOR INSERT TO authenticated
  WITH CHECK (auth.uid()::text = reporter_id);

DROP POLICY IF EXISTS "users can view their own reports" ON public.content_reports;
CREATE POLICY "users can view their own reports" ON public.content_reports
  FOR SELECT TO authenticated
  USING (auth.uid()::text = reporter_id);

-- user blocks (Apple Guideline 1.2)
CREATE TABLE IF NOT EXISTS public.blocked_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  blocker_id text NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
  blocked_id text NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (blocker_id, blocked_id),
  CHECK (blocker_id <> blocked_id)
);

CREATE INDEX IF NOT EXISTS blocked_users_blocker_idx
  ON public.blocked_users (blocker_id);
CREATE INDEX IF NOT EXISTS blocked_users_blocked_idx
  ON public.blocked_users (blocked_id);

ALTER TABLE public.blocked_users ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "users manage their own blocks" ON public.blocked_users;
CREATE POLICY "users manage their own blocks" ON public.blocked_users
  FOR ALL TO authenticated
  USING (auth.uid()::text = blocker_id)
  WITH CHECK (auth.uid()::text = blocker_id);
