-- AI pet assistant (v1.1).
--
-- #1  medical_records: support uploading report photos that are OCR'd once by a
--     vision model. Images live in the private `medical_reports` bucket under
--     `${userId}/...`; we store object PATHS (not signed URLs, which expire) plus
--     the full extracted text so the assistant can answer from it later.
--     The legacy `report_image_url` column is left untouched.
--
-- #2  vaccinations: add vaccine_name — previously only dose_number existed, so
--     neither the user nor the assistant could tell which vaccine was given.
--
-- #3  ai_chat_messages: per-user assistant chat history. Owner-only RLS; users
--     can clear their own history.
--     ai_usage_events: one row per AI call, used for the daily rate limit. Kept
--     separate from chat history (which users may delete) so clearing history
--     can't reset the quota. RLS on with NO policies → only service_role (the
--     Edge Functions) can read/write it.
--     No FK to user_profiles: some auth users have no profile row (2 of 7 live,
--     2026-10-10), which would make inserts fail. Like the health tables, these
--     are deleted explicitly by the delete-account Edge Function instead.
--
-- #4  medical_reports bucket lockdown. Its existing policies ("Allow uploads to
--     medical reports" / "Allow updates to medical reports") only checked
--     bucket_id with no role or owner restriction — anyone, including anon,
--     could write/overwrite any path. It was unused until now; before we start
--     storing real medical photos there, scope everything to the caller's own
--     `${auth.uid()}/` folder (same model as 20260529010000 for avatars/pets).

-- ── #1 ───────────────────────────────────────────────────────────────────
alter table public.medical_records
  add column if not exists report_image_paths text[] not null default '{}',
  add column if not exists report_ocr_text text,
  add column if not exists visit_date date;

-- ── #2 ───────────────────────────────────────────────────────────────────
alter table public.vaccinations
  add column if not exists vaccine_name text;

-- ── #3 ───────────────────────────────────────────────────────────────────
create table if not exists public.ai_chat_messages (
  id uuid primary key default gen_random_uuid(),
  user_id text not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists ai_chat_messages_user_created_idx
  on public.ai_chat_messages (user_id, created_at desc);

alter table public.ai_chat_messages enable row level security;

create policy "ai_chat_messages_select_own" on public.ai_chat_messages
  for select to authenticated
  using ((auth.uid())::text = user_id);
create policy "ai_chat_messages_insert_own" on public.ai_chat_messages
  for insert to authenticated
  with check ((auth.uid())::text = user_id);
create policy "ai_chat_messages_delete_own" on public.ai_chat_messages
  for delete to authenticated
  using ((auth.uid())::text = user_id);

grant select, insert, delete on public.ai_chat_messages to authenticated;

create table if not exists public.ai_usage_events (
  id bigint generated by default as identity primary key,
  user_id text not null,
  kind text not null check (kind in ('chat', 'ocr')),
  created_at timestamptz not null default now()
);

create index if not exists ai_usage_events_user_kind_created_idx
  on public.ai_usage_events (user_id, kind, created_at desc);

alter table public.ai_usage_events enable row level security;
revoke all on public.ai_usage_events from anon, authenticated;

-- ── #4 ───────────────────────────────────────────────────────────────────
-- The bucket was also created PUBLIC (verified live 2026-10-10, 0 objects), so
-- anyone holding an object URL could read it without auth. Medical photos must
-- only be reachable through signed URLs / the owner's JWT.
update storage.buckets set public = false where id = 'medical_reports';

drop policy if exists "Allow uploads to medical reports" on storage.objects;
drop policy if exists "Allow updates to medical reports" on storage.objects;

create policy "medical_reports_select_own" on storage.objects
  for select to authenticated
  using (bucket_id = 'medical_reports' and (storage.foldername(name))[1] = (auth.uid())::text);
create policy "medical_reports_insert_own" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'medical_reports' and (storage.foldername(name))[1] = (auth.uid())::text);
create policy "medical_reports_update_own" on storage.objects
  for update to authenticated
  using (bucket_id = 'medical_reports' and (storage.foldername(name))[1] = (auth.uid())::text)
  with check (bucket_id = 'medical_reports' and (storage.foldername(name))[1] = (auth.uid())::text);
create policy "medical_reports_delete_own" on storage.objects
  for delete to authenticated
  using (bucket_id = 'medical_reports' and (storage.foldername(name))[1] = (auth.uid())::text);
